/**
 * Translates a food name to natural Hindi if Hindi is selected.
 * Falls back gracefully to English if language is English.
 */
export function translateFoodName(englishName: string, isHindi: boolean = true): string {
  if (!isHindi || !englishName) return englishName;

  const normalized = englishName.trim().toLowerCase();

  // 1. Direct match in dictionary
  if (FOOD_NAME_TRANSLATIONS[normalized]) {
    return FOOD_NAME_TRANSLATIONS[normalized];
  }

  // 2. Partial prefix / substring matches
  for (const [key, val] of Object.entries(FOOD_NAME_TRANSLATIONS)) {
    if (normalized.includes(key)) {
      // replace that portion
      const replaced = normalized.replace(key, val);
      return capitalizeHindiWords(replaced);
    }
  }

  // 3. Token-based word-by-word translation
  const words = englishName.split(/\s+/);
  const translatedWords = words.map((w) => {
    const cleanWord = w.toLowerCase().replace(/[^a-z]/g, '');
    if (FOOD_TOKEN_MAP[cleanWord]) {
      return FOOD_TOKEN_MAP[cleanWord];
    }
    return w;
  });

  return translatedWords.join(' ');
}

/**
 * Translates category names (e.g. Starters & Bites -> स्टार्टर्स और स्नैक्स)
 */
export function translateCategoryName(englishCategory: string, isHindi: boolean = true): string {
  if (!isHindi || !englishCategory) return englishCategory;

  const normalized = englishCategory.trim().toLowerCase();
  if (CATEGORY_TRANSLATIONS[normalized]) {
    return CATEGORY_TRANSLATIONS[normalized];
  }

  for (const [key, val] of Object.entries(CATEGORY_TRANSLATIONS)) {
    if (normalized.includes(key)) {
      return val;
    }
  }

  return englishCategory;
}

